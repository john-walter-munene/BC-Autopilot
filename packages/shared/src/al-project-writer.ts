/**
 * AL Project Writer
 * Phase 1: materialises a generated AL suite (app.json + .al objects) into a real project folder
 * that `alc.exe` can compile.
 */

import fs from 'node:fs';
import path from 'node:path';
import { BC_CONSTANTS } from './constants.ts';
import type { AppJsonManifest, AlExtensionFile } from './types.ts';
import type { AlProjectWriteRequest, AlProjectWriteResult } from './al-cli-types.ts';

export interface AlProjectWriterDeps {
  mkdir?: (dir: string) => void;
  writeFile?: (filePath: string, data: string) => void;
  readFile?: (filePath: string) => string;
  fileExists?: (filePath: string) => boolean;
}

/**
 * Build the full `app.json` payload written to disk.
 * The generated manifest is intentionally minimal; the writer fills in the AppSource-required fields.
 */
export function buildAppJson(manifest: AppJsonManifest, overrides: Pick<AlProjectWriteRequest, 'publisher' | 'application' | 'platform'> = {}): Record<string, unknown> {
  return {
    id: manifest.id,
    name: manifest.name,
    publisher: overrides.publisher ?? BC_CONSTANTS.DEFAULT_PUBLISHER,
    version: manifest.version,
    brief: manifest.name,
    description: `${manifest.name} â€” generated by Alchemy365.`,
    privacyStatement: 'https://example.com/privacy',
    EULA: 'https://example.com/eula',
    help: 'https://example.com/help',
    url: 'https://example.com',
    dependencies: [],
    screenshots: [],
    platform: overrides.platform ?? '1.0.0.0',
    application: overrides.application ?? '24.0.0.0',
    idRanges: manifest.idRanges,
    resourceExposurePolicy: {
      allowDebugging: true,
      allowDownloadingSource: false,
      includeSourceInSymbolFile: true,
    },
    runtime: manifest.runtime,
    target: manifest.target,
  };
}

/**
 * Sanitise a file name so it is safe to write on Windows and Linux.
 */
export function sanitiseFileName(fileName: string): string {
  const base = path.basename(fileName).replace(/[<>:"/\\|?*\u0000-\u001F]/g, '_');
  return base.length > 0 ? base : 'object.al';
}

export class AlProjectWriter {
  private readonly deps: Required<AlProjectWriterDeps>;

  constructor(deps: AlProjectWriterDeps = {}) {
    this.deps = {
      mkdir: deps.mkdir ?? ((dir: string) => fs.mkdirSync(dir, { recursive: true })),
      writeFile: deps.writeFile ?? ((filePath: string, data: string) => fs.writeFileSync(filePath, data, 'utf8')),
      readFile: deps.readFile ?? ((filePath: string) => fs.readFileSync(filePath, 'utf8')),
      fileExists: deps.fileExists ?? ((filePath: string) => fs.existsSync(filePath)),
    };
  }

  /**
   * Write the AL project to disk and return the paths that were created.
   */
  writeProject(request: AlProjectWriteRequest): AlProjectWriteResult {
    const projectPath = path.resolve(request.outDir);
    this.deps.mkdir(projectPath);

    const appJson = buildAppJson(request.manifest, request);
    const appJsonPath = path.join(projectPath, 'app.json');
    this.deps.writeFile(appJsonPath, `${JSON.stringify(appJson, null, 2)}\n`);

    const writtenFiles: string[] = [appJsonPath];
    const seen = new Set<string>(['app.json']);

    for (const file of request.files) {
      const fileName = sanitiseFileName(file.fileName);
      if (seen.has(fileName.toLowerCase())) continue;
      seen.add(fileName.toLowerCase());

      const filePath = path.join(projectPath, fileName);
      this.deps.writeFile(filePath, file.codeContent);
      writtenFiles.push(filePath);
    }

    return {
      projectPath,
      appJsonPath,
      writtenFiles,
      manifest: request.manifest,
    };
  }

  /**
   * Read back the `app.json` of an existing project (used by the CLI and tests).
   */
  readAppJson(projectPath: string): Record<string, unknown> {
    const appJsonPath = path.join(path.resolve(projectPath), 'app.json');
    return JSON.parse(this.deps.readFile(appJsonPath)) as Record<string, unknown>;
  }

  /**
   * List the `.al` files in a project folder.
   */
  listAlFiles(projectPath: string): string[] {
    const resolved = path.resolve(projectPath);
    if (!this.deps.fileExists(resolved)) return [];
    return fs
      .readdirSync(resolved)
      .filter(fileName => fileName.toLowerCase().endsWith('.al'))
      .sort();
  }
}

export const alProjectWriter = new AlProjectWriter();
