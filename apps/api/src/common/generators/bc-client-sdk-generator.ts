/**
 * Business Central client SDK generator.
 * Emits the integration client for an imported Next.js app.
 *
 * Token acquisition is delegated to `@bc-agent/shared`'s `EntraIdTokenProvider` so there is
 * exactly one implementation of caching, refresh, retry and redaction in the platform.
 */

/** Company-scoped OData root the generated client talks to. */
export const DEFAULT_API_PATH = 'api/alc/integrations/v2.0';

export interface BcClientSdkOptions {
  /** Imported repository, mentioned in the generated header */
  repoUrlOrPath: string;
}

export function generateBcClientSdk(repoUrlOrPath: string): string {
  return `/**
 * Drop-in Business Central client SDK for the imported Next.js app.
 * Generated by BC Autopilot in the context of ${repoUrlOrPath}
 *
 * Requires the workspace package \`@bc-agent/shared\`, which owns Entra ID token handling
 * (per-tenant cache, early refresh, retry with backoff, secret redaction).
 */

import { EntraIdTokenProvider } from '@bc-agent/shared';

interface ClientConfig {
  tenantId: string;
  clientId: string;
  clientSecret: string;
  environment: string;
  companyId: string;
}

function readConfig(): ClientConfig {
  const config = {
    tenantId: process.env.BC_TENANT_ID ?? '',
    clientId: process.env.BC_CLIENT_ID ?? '',
    clientSecret: process.env.BC_CLIENT_SECRET ?? '',
    environment: process.env.BC_ENVIRONMENT ?? 'Sandbox',
    companyId: process.env.BC_COMPANY_ID ?? '',
  };

  const missing = Object.entries(config)
    .filter(([key, value]) => key !== 'environment' && !value)
    .map(([key]) => key);

  if (missing.length > 0) {
    throw new Error(\`Business Central configuration is incomplete: missing \${missing.join(', ')}\`);
  }

  return config;
}

export async function getBcAuthenticatedClient() {
  const config = readConfig();
  const provider = new EntraIdTokenProvider();

  const baseUrl =
    \`https://api.businesscentral.dynamics.com/v2.0/\${config.tenantId}/\${config.environment}/\${'${DEFAULT_API_PATH}'}/companies(\${config.companyId})\`;

  async function request<T>(path: string, init: { method?: string; body?: unknown } = {}): Promise<T> {
    const token = await provider.getToken(config);
    const response = await fetch(\`\${baseUrl}/\${path}\`, {
      method: init.method ?? 'GET',
      headers: {
        Authorization: \`Bearer \${token.accessToken}\`,
        Accept: 'application/json',
        ...(init.body === undefined ? {} : { 'Content-Type': 'application/json' }),
      },
      body: init.body === undefined ? undefined : JSON.stringify(init.body),
    });

    if (!response.ok) {
      throw new Error(\`Business Central request failed (\${response.status}) for \${path}\`);
    }

    return (await response.json()) as T;
  }

  return {
    getCustomerProfiles: () => request<{ value: unknown[] }>('customerProfiles'),
    submitOnlineOrder: (payload: Record<string, unknown>) =>
      request<Record<string, unknown>>('onlineOrders', { method: 'POST', body: payload }),
  };
}
`;
}

export const bcClientSdkGenerator = { generate: generateBcClientSdk };
